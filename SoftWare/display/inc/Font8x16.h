/**
  ******************************************************************************
  * @file    SoftWare/inc/Font8x16.h
  * @brief   8x16 ASCII 点阵字库(覆盖 0x20~0x7E 可见字符)
  *
  *          2026-09-22 从 OLED_Font 改名而来。原名带误导: 这张表虽然是从
  *          SSD1306 那套 OLED 驱动里搬过来的, 但现在只有 LCD.c 在用 ——
  *          项目里已经没有 OLED 了。名字该描述"这是什么", 不是"从哪来"。
  *
  *          ⚠ 存储方式和中文字模(CN_Font.h)**不一样**, 混用会得到转置或翻转
  *            的乱码:
  *              本表   —— **按列**存, 一个字节 = 一列 8 个像素, **bit0 在最上面**
  *                        (SSD1306 的页结构就是这样, 江科大那套驱动一次写一个
  *                         字节正好对应一整列)
  *              汉字表 —— **按行**存, 每行 2 字节, 高位在左
  *
  *          每个字符 16 字节: [0..7] 上半部分, [8..15] 下半部分。
  *          验证方法: 把 '_' 画出来, 应该在**最后一行**而不是中间。
  ******************************************************************************
  */

